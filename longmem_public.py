"""Adapter: the PUBLIC LongMemEval oracle dataset -> harness Cases.

This is a different source/schema than longmem_fixture.py (which parses Honcho's
own tests/unified/test_cases/longmem_*.json). Here we read the public
`longmemeval_oracle.json` from xiaowu0162/LongMemEval. The oracle variant keeps
only the evidence sessions per question, so each conversation is small enough to
fit a local 32K context.

Public instance fields:
  question_id     str   (ids ending in "_abs" are abstention questions)
  question_type   str   (single-session-*, multi-session, temporal-reasoning, knowledge-update, ...)
  question        str
  answer          str   (ground-truth gold)
  question_date   str
  haystack_sessions  list[ list[ {role, content, has_answer?} ] ]   (oracle = evidence only)
  answer_session_ids list[str]

HONESTY NOTES (same as the fixture adapter):
  * `actual` is generated by the LOCAL model, NOT Honcho's system -- this tests
    the JUDGE on real benchmark data; it is not an audit of Honcho.
  * We STRIP the per-turn `has_answer` flag when rendering context -- leaving it
    in would leak the evidence location to the model/judge (unfair).
  * `human_label` is left None (actual is generated, so no a-priori ground truth);
    read results with label_view, not compare's accuracy.
  * oracle-scale only -- the full _s / _m haystacks (~115K+ tokens) do NOT fit.
"""

import json
import random
from collections import defaultdict
from pathlib import Path

from harness import Case


def _render_sessions(haystack_sessions) -> str:
    """Flatten evidence sessions into 'User:' / 'Assistant:' lines. Drops has_answer."""
    lines = []
    for session in haystack_sessions or []:
        for turn in session:
            who = str(turn.get("role", "?")).capitalize()
            lines.append(f"{who}: {turn.get('content', '')}")
    return "\n".join(lines)


def parse_oracle(path) -> list[dict]:
    """Pure parse (no model calls): oracle file -> list of record dicts.

    Each record: {id, question, expected, context, question_type, is_abstention}.
    """
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    out = []
    for inst in data:
        qid = inst.get("question_id", "")
        question = inst.get("question", "").strip()
        date = inst.get("question_date", "")
        # LongMemEval presents the question with its date; temporal-reasoning needs it.
        if date:
            question = f"[{date}] {question}"
        out.append({
            "id": qid,
            "question": question,
            "expected": str(inst.get("answer", "")).strip(),
            "context": _render_sessions(inst.get("haystack_sessions")),
            "question_type": inst.get("question_type", "unknown"),
            "is_abstention": qid.endswith("_abs"),
        })
    return out


def sample(records: list[dict], n: int, seed: int = 0, abstention_frac: float = 0.3) -> list[dict]:
    """Pick ~n records: guarantee an abstention share, round-robin the rest by type."""
    rng = random.Random(seed)
    abst = [r for r in records if r["is_abstention"]]
    rest = [r for r in records if not r["is_abstention"]]
    rng.shuffle(abst)

    n_abst = min(len(abst), round(n * abstention_frac))
    picked = abst[:n_abst]

    # round-robin the non-abstention remainder across question types for spread
    by_type = defaultdict(list)
    for r in rest:
        by_type[r["question_type"]].append(r)
    for v in by_type.values():
        rng.shuffle(v)
    types = list(by_type)
    idx = 0
    while len(picked) < n and any(by_type.values()):
        t = types[idx % len(types)]
        if by_type[t]:
            picked.append(by_type[t].pop())
        idx += 1

    rng.shuffle(picked)
    return picked


def _generate_actual(client, model, context: str, question: str) -> str:
    """Answer the question from the conversation; abstain if it isn't there."""
    prompt = (
        "You are a helpful assistant with memory of the conversation below. "
        "Answer the user's final question using only what the conversation supports. "
        "If the conversation does not contain the answer, say you don't have that information.\n\n"
        f"Conversation:\n{context}\n\nQuestion: {question}\nAnswer:"
    )
    resp = client.chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": prompt}],
        temperature=0.0,
    )
    return resp.choices[0].message.content.strip()


def load_public_cases(path, client, model, n: int = 30, seed: int = 0) -> list[Case]:
    """Sample ~n oracle questions, generate a local answer for each, return Cases."""
    records = sample(parse_oracle(path), n=n, seed=seed)
    cases = []
    for rec in records:
        actual = _generate_actual(client, model, rec["context"], rec["question"])
        cases.append(Case(
            id=rec["id"],
            question=rec["question"],
            expected=rec["expected"],
            actual=actual,
            context=rec["context"],
            question_type=rec["question_type"],
            human_label=None,
        ))
    return cases
